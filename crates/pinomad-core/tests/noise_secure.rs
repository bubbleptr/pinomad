// ─── SecureConnection / SecureTransport behavior ─────────────────────────────

/// Drive a connection generation end-to-end with an in-test responder.
fn drive_handshake(
    connection: &mut dyn Connection,
    host: &KeyPair,
) -> (String, Vec<ConnOut>) {
    let mut out = Vec::new();
    connection.opened(&mut out);
    let msg1 = out
        .iter()
        .find_map(|o| match o {
            ConnOut::SendBytes(b) => Some(b.clone()),
            _ => None,
        })
        .expect("message 1 emitted");
    let mut responder = respond_handshake(host).unwrap();
    let (hello, _remote) = responder.read_message1(&msg1).unwrap();
    let (message2, _session) = responder.write_message2(&pinomad_core::secure_channel::encode_host_hello()).unwrap();
    let start = out.len();
    connection.data(&message2, &mut out);
    (hello, out.split_off(start))
}

#[test]
fn connection_sends_pairing_once_and_reports_paired() {
    let host = generate_keypair().unwrap();
    let (device, device_private_b64) = SecureTransport::new_device().unwrap();
    let _ = device;
    let mut transport = SecureTransport::new(
        "ws://127.0.0.1:1",
        &to_base64url(&host.public_key),
        &device_private_b64,
        Some(Pairing { secret: "one-time".into(), name: "phone".into() }),
    )
    .unwrap();

    // First generation: hello carries the pair block, Paired fires once.
    let mut conn = transport.open();
    let (hello, after) = drive_handshake(&mut *conn, &host);
    let (_, pair) = decode_client_hello(&hello).unwrap();
    let pair = pair.expect("first hello carries pair");
    assert_eq!(pair.secret, "one-time");
    assert!(after.iter().any(|o| matches!(o, ConnOut::Paired)));
    transport.mark_paired();

    // Second generation: no pair block, no Paired.
    let mut conn = transport.open();
    let (hello, after) = drive_handshake(&mut *conn, &host);
    let (_, pair) = decode_client_hello(&hello).unwrap();
    assert!(pair.is_none());
    assert!(!after.iter().any(|o| matches!(o, ConnOut::Paired)));
}

#[test]
fn connection_closes_1008_on_garbage_message2() {
    let host = generate_keypair().unwrap();
    let device = generate_keypair().unwrap();
    let mut conn = SecureConnection::new(&device, host.public_key, None).unwrap();
    let mut out = Vec::new();
    conn.opened(&mut out);
    conn.data(&[9, 9, 9, 9], &mut out);
    let closed = out.iter().find_map(|o| match o {
        ConnOut::Closed { code, reason } => Some((*code, reason.clone())),
        _ => None,
    });
    assert!(out.iter().any(|o| matches!(o, ConnOut::Close)));
    assert_eq!(closed.as_ref().map(|(c, _)| *c), Some(1008));
}

#[test]
fn connection_queues_frames_until_ready() {
    let host = generate_keypair().unwrap();
    let device = generate_keypair().unwrap();
    let mut conn = SecureConnection::new(&device, host.public_key, None).unwrap();
    let mut out = Vec::new();
    // A send before open: queued, nothing emitted.
    conn.send("{\"type\":\"hello\"}".into(), &mut out);
    assert!(out.is_empty());
    let (_hello, after) = drive_handshake(&mut conn, &host);
    // The queued frame flushes as sealed records after the handshake.
    assert!(after.iter().any(|o| matches!(o, ConnOut::SendBytes(_))));
}
