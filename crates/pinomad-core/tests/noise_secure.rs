// Ports of packages/protocol/test/{noise,secure-channel}.test.ts plus a
// replay of the generated record-layer vectors. The Cacophony vectors pin
// snow's wire bytes; the rejection paths pin the poisoning semantics the
// record layer gives the session.

use std::path::PathBuf;

use pinomad_core::b64::{from_base64url, to_base64url};
use pinomad_core::json::Json;
use pinomad_core::noise::{
    generate_keypair, initiate_ik, keypair_from_private, respond_ik, InitiateOptions, KeyPair,
    RespondOptions,
};
use pinomad_core::secure_channel::{
    decode_client_hello, decode_host_hello, encode_client_hello, respond_handshake, Pairing,
    SecureConnection, SecureSession, SecureTransport, SECURE_PROLOGUE,
};
use pinomad_core::transport::{ConnOut, Connection, Transport};

fn fixtures() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol/test/fixtures")
}

fn load(name: &str) -> Json {
    let text = std::fs::read_to_string(fixtures().join(format!("{name}.json"))).unwrap();
    Json::parse(&text).unwrap()
}

fn text(value: &Json, key: &str) -> String {
    value.get(key).unwrap().as_str().unwrap().to_string_lossy()
}

fn unhex(text: &str) -> Vec<u8> {
    assert!(text.len() % 2 == 0);
    (0..text.len() / 2)
        .map(|i| u8::from_str_radix(&text[i * 2..i * 2 + 2], 16).unwrap())
        .collect()
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn unhex_key(text: &str) -> [u8; 32] {
    unhex(text).try_into().expect("32-byte key")
}

fn kp(private: &str) -> KeyPair {
    keypair_from_private(&unhex(private)).unwrap()
}

// ─── Cacophony vectors ───────────────────────────────────────────────────────

#[test]
fn noise_ik_vectors_match_byte_for_byte() {
    let file = load("noise-ik-vectors");
    for vector in file.get("vectors").unwrap().as_array().unwrap().iter() {
        let init_static = kp(&text(vector, "init_static"));
        let init_eph = kp(&text(vector, "init_ephemeral"));
        let resp_static = kp(&text(vector, "resp_static"));
        let resp_eph = kp(&text(vector, "resp_ephemeral"));
        let remote_static = unhex_key(&text(vector, "init_remote_static"));

        let messages: Vec<(Vec<u8>, Vec<u8>)> = vector
            .get("messages")
            .unwrap()
            .as_array()
            .unwrap()
            .iter()
            .map(|m| (unhex(&text(m, "payload")), unhex(&text(m, "ciphertext"))))
            .collect();
        let (first, second, transport) = (messages[0].clone(), messages[1].clone(), &messages[2..]);

        let initiator = initiate_ik(InitiateOptions {
            prologue: &unhex(&text(vector, "init_prologue")),
            device: &init_static,
            remote_static,
            payload: &first.0,
            ephemeral: Some(&init_eph),
        })
        .unwrap();
        assert_eq!(hex(&initiator.message1), hex(&first.1));

        let mut responder = respond_ik(RespondOptions {
            prologue: &unhex(&text(vector, "resp_prologue")),
            host: &resp_static,
            ephemeral: Some(&resp_eph),
        })
        .unwrap();
        let (payload, seen_remote) = responder.read_message1(&first.1).unwrap();
        assert_eq!(payload, first.0);
        assert_eq!(seen_remote, init_static.public_key);

        let (message2, responder_result) = responder.write_message2(&second.0).unwrap();
        assert_eq!(message2, second.1);

        let (host_payload, initiator_result) = initiator.read_message2(&second.1).unwrap();
        assert_eq!(host_payload, second.0);
        assert_eq!(hex(&initiator_result.handshake_hash), text(vector, "handshake_hash"));
        assert_eq!(hex(&responder_result.handshake_hash), text(vector, "handshake_hash"));

        // Transport messages alternate initiator→responder, responder→initiator.
        let mut initiator_transport = initiator_result.transport;
        let mut responder_transport = responder_result.transport;
        for (index, (payload, ciphertext)) in transport.iter().enumerate() {
            let (sender, receiver) = if index % 2 == 0 {
                (&mut initiator_transport, &mut responder_transport)
            } else {
                (&mut responder_transport, &mut initiator_transport)
            };
            let mut buf = vec![0u8; payload.len() + 16];
            let len = sender.write_message(payload, &mut buf).unwrap();
            assert_eq!(hex(&buf[..len]), hex(ciphertext), "transport {index}");
            let mut plain = vec![0u8; ciphertext.len()];
            let out = receiver.read_message(ciphertext, &mut plain).unwrap();
            assert_eq!(plain[..out], payload[..], "transport {index}");
        }
    }
}

// ─── Record-layer vectors (generated by the TS reference) ────────────────────

#[test]
fn record_vectors_match_the_reference() {
    let file = load("rust-vectors/records");
    let keys = file.get("keys").unwrap();
    let device_static = kp(&text(keys, "deviceStatic"));
    let device_eph = kp(&text(keys, "deviceEphemeral"));
    let host_static = kp(&text(keys, "hostStatic"));
    let host_eph = kp(&text(keys, "hostEphemeral"));
    let hellos = file.get("hellos").unwrap();

    let initiator = initiate_ik(InitiateOptions {
        prologue: SECURE_PROLOGUE,
        device: &device_static,
        remote_static: unhex_key(&text(keys, "hostStaticPublic")),
        payload: text(hellos, "client").as_bytes(),
        ephemeral: Some(&device_eph),
    })
    .unwrap();
    assert_eq!(hex(&initiator.message1), text(&file, "message1"));

    let mut responder = respond_ik(RespondOptions {
        prologue: SECURE_PROLOGUE,
        host: &host_static,
        ephemeral: Some(&host_eph),
    })
    .unwrap();
    let (payload, remote) = responder.read_message1(&initiator.message1).unwrap();
    assert_eq!(hex(&payload), text(&file, "clientPayload"));
    assert_eq!(hex(&remote), text(&file, "remoteStaticSeen"));
    assert_eq!(remote, device_static.public_key);

    let (message2, server_result) = responder.write_message2(text(hellos, "host").as_bytes()).unwrap();
    assert_eq!(hex(&message2), text(&file, "message2"));

    let (host_payload, client_result) = initiator.read_message2(&message2).unwrap();
    assert_eq!(hex(&host_payload), text(&file, "hostPayload"));
    assert_eq!(hex(&client_result.handshake_hash), text(&file, "handshakeHash"));

    let mut client = SecureSession::new(client_result.transport);
    let mut server = SecureSession::new(server_result.transport);

    for case in file.get("records").unwrap().as_array().unwrap().iter() {
        let name = text(case, "name");
        let expected_chunks: Vec<Vec<u8>> = case
            .get("chunks")
            .unwrap()
            .as_array()
            .unwrap()
            .iter()
            .map(|c| unhex(&c.as_str().unwrap().to_string_lossy()))
            .collect();
        let (sender, receiver) = if text(case, "direction") == "c2s" {
            (&mut client, &mut server)
        } else {
            (&mut server, &mut client)
        };
        let text_value = text(case, "text");
        let chunks = sender.seal(&text_value).unwrap_or_else(|e| panic!("{name}: seal: {e}"));
        assert_eq!(chunks, expected_chunks, "{name}");
        let mut opened = None;
        for chunk in &expected_chunks {
            if let Some(text) = receiver.open(chunk).unwrap_or_else(|e| panic!("{name}: open: {e}")) {
                opened = Some(text);
            }
        }
        assert_eq!(opened.as_deref(), Some(text_value.as_str()), "{name}");
    }
}

// ─── Hello codec ─────────────────────────────────────────────────────────────

#[test]
fn hello_codecs_round_trip_and_reject() {
    assert_eq!(encode_client_hello(None), "{\"v\":1}");
    let (version, pair) = decode_client_hello(&encode_client_hello(Some(&Pairing {
        secret: "s".into(),
        name: "phone".into(),
    })))
    .unwrap();
    assert_eq!(version, 1);
    assert_eq!(pair.unwrap().name, "phone");
    assert!(decode_host_hello("{\"v\":1}").is_ok());

    // Every rejection the reference throws on.
    assert!(decode_client_hello(&String::from_utf8_lossy(&[1, 2, 3])).is_err());
    assert!(decode_client_hello("{\"v\":2}").is_err());
    assert!(decode_host_hello("{\"v\":2}").is_err());
    assert!(decode_client_hello("{}").is_err());
    assert!(decode_client_hello("{\"v\":1,\"pair\":{\"secret\":1}}").is_err());
}

#[test]
fn base64url_round_trips_and_rejects() {
    for size in [1usize, 2, 3, 32, 33, 64] {
        let bytes: Vec<u8> = (0..size).map(|i| (i * 31 + 7) as u8).collect();
        assert_eq!(from_base64url(&to_base64url(&bytes)).unwrap(), bytes);
    }
    assert_eq!(to_base64url(&[255, 255, 255]), "____");
    assert!(from_base64url("abc=").is_err());
    assert!(from_base64url("abcde").is_err());
    assert!(from_base64url("e").is_err());
}

// ─── Session-level rejection paths ───────────────────────────────────────────

fn handshake_pair() -> (SecureSession, SecureSession) {
    let host = generate_keypair().unwrap();
    let device = generate_keypair().unwrap();
    let client = initiate_ik(InitiateOptions {
        prologue: SECURE_PROLOGUE,
        device: &device,
        remote_static: host.public_key,
        payload: b"",
        ephemeral: None,
    })
    .unwrap();
    let mut server = respond_ik(RespondOptions { prologue: SECURE_PROLOGUE, host: &host, ephemeral: None }).unwrap();
    server.read_message1(&client.message1).unwrap();
    let (message2, server_result) = server.write_message2(b"").unwrap();
    let (_payload, client_result) = client.read_message2(&message2).unwrap();
    (
        SecureSession::new(client_result.transport),
        SecureSession::new(server_result.transport),
    )
}

#[test]
fn session_round_trips() {
    let (mut client, mut server) = handshake_pair();
    let chunks = client.seal("{\"type\":\"subscribe\",\"stream\":\"tasks\"}").unwrap();
    assert_eq!(chunks.len(), 1);
    assert_eq!(server.open(&chunks[0]).unwrap().as_deref(), Some("{\"type\":\"subscribe\",\"stream\":\"tasks\"}"));

    let unicode = "中文消息 ✓ emoji 🚀 done";
    for chunk in client.seal(unicode).unwrap() {
        let _ = server.open(&chunk).unwrap();
    }
    // A large frame splits at the record boundary.
    let big = "x".repeat(200 * 1024) + "tail 中文";
    let chunks = client.seal(&big).unwrap();
    assert!(chunks.len() > 1);
    for chunk in &chunks {
        assert!(chunk.len() <= 65535);
    }
    let mut last = None;
    for chunk in &chunks {
        last = server.open(chunk).unwrap().or(last);
    }
    assert_eq!(last.as_deref(), Some(big.as_str()));

    // Empty frame: one record.
    let chunks = server.seal("").unwrap();
    assert_eq!(chunks.len(), 1);
    assert_eq!(client.open(&chunks[0]).unwrap().as_deref(), Some(""));
}

#[test]
fn session_rejects_tampered_replayed_reordered_and_wrong_direction() {
    let (mut client, mut server) = handshake_pair();

    // Tampering.
    let chunk = client.seal("hello").unwrap().remove(0);
    let mut bad = chunk.clone();
    bad[3] ^= 1;
    assert!(server.open(&bad).is_err());
    // Poisoning: the good copy fails too once a record failed — the JS
    // cipher's nonce already advanced past it.
    assert!(server.open(&chunk).is_err());

    // Fresh channel for replay.
    let (mut client, mut server) = handshake_pair();
    let chunk = client.seal("hello").unwrap().remove(0);
    assert!(server.open(&chunk).is_ok());
    assert!(server.open(&chunk).is_err());

    // Reordering wedges the session: after open(second) fails, even the
    // in-order first cannot arrive.
    let (mut client, mut server) = handshake_pair();
    let first = client.seal("one").unwrap().remove(0);
    let second = client.seal("two").unwrap().remove(0);
    assert!(server.open(&second).is_err());
    assert!(server.open(&first).is_err());

    // Wrong direction: two sessions over the same send cipher.
    let (client, _server) = handshake_pair();
    let mut a = client;
    let mut b = a.fork();
    let chunk = a.seal("same keys, wrong role").unwrap().remove(0);
    assert!(b.open(&chunk).is_err());
}

#[test]
fn a_failed_open_on_one_fork_wedges_the_other_fork() {
    let (mut client, server) = handshake_pair();
    let mut a = server;
    let mut b = a.fork();

    // A bad record on `a` poisons the shared receive direction...
    let mut bad = vec![0xde, 0xad, 0xbe, 0xef];
    bad.extend_from_slice(&[0; 32]);
    assert!(a.open(&bad).is_err());

    // ...so a perfectly good record on `b` fails too — the wedge lives in
    // the shared cipher state, not in the session object.
    let chunk = client.seal("valid").unwrap().remove(0);
    assert!(b.open(&chunk).is_err());
    assert!(a.open(&chunk).is_err());
}

